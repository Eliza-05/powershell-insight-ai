def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def terminal(summary, thresholds):
    stage = summary["stages"]["selection"]
    planned, attempted, usable = (stage[k] for k in ("planned", "attempted", "usable"))
    maximum = usable + planned - attempted
    required = thresholds["mandatory_proposed"]["schema_valid_all_calls_rate"]
    ineligible = maximum / planned < required
    return {"state": "closed_ineligible_no_approval" if ineligible else "incomplete_no_approval",
            "planned": planned, "attempted": attempted, "usable": usable,
            "not_executed": planned - attempted, "maximum_possible_usable": maximum,
            "maximum_possible_rate": maximum / planned, "required_rate": required,
            "mandatory_gate_unreachable": ineligible, "classification_failure_inferred": False,
            "valid_approval_by_resuming_original_run": not ineligible,
            "historical_outputs_modified": False, "model_approved": False}


