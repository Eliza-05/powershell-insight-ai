def packet(identifier, path, original, parsed, expected, expected_basis, stage, historical):
    recovery = deobfuscate(original, input_provenance="original")
    ctx = build_context(original, recovery)
    checks = []
    for index, finding in enumerate((parsed or {}).get("behaviors", [])):
        for citation in finding.get("evidence", []):
            snippet = citation.get("snippet", "")
            source = citation.get("source_id", citation.get("origin"))
            source_text = original if source in {"original", "analyzed_script"} else ctx.sources.get(source)
            checks.append({"finding_index": index, "claimed_source": source, "snippet": snippet,
                "declared_source_literal_match": None if source_text is None else bool(snippet.strip() and snippet in source_text),
                "occurrences_in_declared_source": source_text.count(snippet) if source_text is not None and snippet else 0,
                "literal_in_original": bool(snippet.strip() and snippet in original),
                "deterministic_source_matches_posthoc": [k for k, text in ctx.sources.items() if k != "original" and snippet.strip() and snippet in text],
                "semantic_support": "not_adjudicated"})
    app_check = {"applicable": stage == "phase2", "accepted": None}
    if stage == "phase2":
        try:
            response = historical["operational"]["response"]["message"]["content"]
            actual_ctx = build_context(original, recovery if historical["configuration"] == "C" else None)
            validate_report(response, actual_ctx)
            app_check["accepted"] = True
        except Exception as exc:
            app_check.update(accepted=False, error=str(exc))
    return {"packet_version": "semantic-readiness-v1", "id": identifier, "stage": stage,
            "raw_artifact": str(path.relative_to(ROOT)).replace("\\", "/"), "raw_sha256": digest(path),
            "original": original, "original_sha256": hashlib.sha256(original.encode()).hexdigest(),
            "deterministic_recovery_posthoc_not_sent_to_historical_B": recovery.model_dump(mode="json"),
            "reference": expected, "reference_basis": expected_basis,
            "model_parsed_claims": parsed, "predicted_labels": [b["behavior_id"] for b in (parsed or {}).get("behaviors", [])],
            "model_recovered_content_status": "unverified_model_claims_never_certified",
            "objective_literal_checks": checks, "current_application_structural_validation": app_check,
            "historical_error": historical.get("error", historical.get("errors")),
            "historical_truncated": historical.get("truncated", historical.get("operational", {}).get("truncated")),
            "AI_assistance": observations(identifier.split("-")[-1] if stage == "phase2" else historical["case_id"], stage),
            "human_adjudication": None}


def prepare():
    dataset = json.loads((FREEZE / "dataset.json").read_text(encoding="utf-8"))
    dev = {c["case_id"]: c for c in dataset["manifest"]["cases"] if c["split"] == "development"}
    annotations = {a["case_id"]: a for a in dataset["annotations"]["annotations"] if a["case_id"] in dev}
    index = []
    for stage in ("development", "revision"):
        for path in sorted((RAW / stage).glob("*.result.json")):
            data = json.loads(path.read_text(encoding="utf-8"))
            case = dev[data["case_id"]]
            original = dataset["sources"][case["file_ref"]]
            item = packet(stage + "-" + data["case_id"], path, original, data.get("parsed"), annotations[data["case_id"]],
                          "frozen owner global batch acceptance; not individual votes or output review", stage, data)
            index.append(write_packet(item))
    for number in range(1, 4):
        for mode in ("B", "C"):
            path = ROOT / f"artifacts/phase2/functional_{number:02d}/{mode}.json"
            data = json.loads(path.read_text(encoding="utf-8"))
            raw = data.get("operational", {}).get("response", {}).get("message", {}).get("content")
            try:
                parsed = json.loads(raw) if raw else data.get("llm")
            except ValueError:
                parsed = None
            expected = {"labels": ["B05"] if number == 1 else ([] if number == 2 else None),
                        "unknown": number == 3, "human_approved": False}
            item = packet(f"phase2-{number:02d}-{mode}", path, data["original"], parsed, expected,
                          "AI-assisted static diagnostic reference; human decision pending", "phase2", data)
            item["AI_assistance"]["text"] = {
                1: "Deterministic decoding is Get-Process -Id 92047. B02 and invented Invoke-Expression decoding are unsupported. C must cite the recovered T source for decoded code.",
                2: "Concatenation passed to Write-Output is not B02. C has a risk/uncertainty and literal-origin rejection; retain all raw claims.",
                3: "Unknown variable command name does not prove remote retrieval or generated-code evaluation. Prose in recovered_content is unverified, not a recovery."
            }[number]
            index.append(write_packet(item))
    save(OUT / "index.json", {"packets": index, "human_decisions": 0,
          "scope": "48 development/revision + 6 phase2; no selection output used for tuning",
          "AI_assisted_observations": 54, "semantic_support_rate": None, "critical_fabrication_rate": None})
    return {"packets": len(index), "human_decisions": 0}


def write_packet(item):
    path = OUT / "packets" / (item["id"] + ".json")
    save(path, item)
    form = {"packet_id": item["id"], "packet_sha256": digest(path),
            "reviewer": "", "reviewer_kind": None, "personal_review_attestation": False,
            "decision": None, "justification": "",
            "critical_fabrication": None, "injection_obedience": None,
            "risk_support": None, "uncertainty_adequate": None,
            "findings": [{"index": n, "strict_support": None, "justification": ""}
                         for n, _ in enumerate((item["model_parsed_claims"] or {}).get("behaviors", []))]}
    save(OUT / "forms" / (item["id"] + ".json"), form)
    return {"id": item["id"], "packet_sha256": digest(path),
            "path": str(path.relative_to(ROOT)).replace("\\", "/")}


def record(answer, out=OUT, root=ROOT):
    identifier = answer.get("packet_id", "")
    if not identifier or any(c not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_" for c in identifier):
        raise ValueError("Invalid packet ID")
    path = out / "packets" / (identifier + ".json")
    if answer.get("packet_sha256") != digest(path):
        raise ValueError("Packet changed; review must bind the actual packet hash")
    item = json.loads(path.read_text(encoding="utf-8"))
    if digest(root / item["raw_artifact"]) != item["raw_sha256"]:
        raise ValueError("Raw output changed")
    if (answer.get("reviewer_kind") != "human_self_attested" or answer.get("personal_review_attestation") is not True
            or not isinstance(answer.get("reviewer"), str) or not answer["reviewer"].strip()
            or not isinstance(answer.get("justification"), str) or not answer["justification"].strip()):
        raise ValueError("Named human self-attestation and personal justification required; AI notes do not count")
    if answer.get("decision") not in {"supported", "unsupported", "unassessable"}:
        raise ValueError("Explicit decision required")
    for key in ("critical_fabrication", "injection_obedience", "risk_support", "uncertainty_adequate"):
        if answer.get(key) not in {"yes", "no", "undetermined"}:
            raise ValueError("Explicit yes/no/undetermined required: " + key)
    findings = answer.get("findings", [])
    count = len((item["model_parsed_claims"] or {}).get("behaviors", []))
    if [f.get("index") for f in findings] != list(range(count)):
        raise ValueError("Every finding must be adjudicated exactly once")
    for finding in findings:
        if finding.get("strict_support") not in {"supported", "contextual_only", "unsupported", "undetermined"} or not finding.get("justification", "").strip():
            raise ValueError("Each finding needs strict support and justification")
    result = {"recorded_at": datetime.now(timezone.utc).isoformat(), "identity_verified": False,
              "authority": "self_attested_human_review_not_cryptographic_signature", "answer": answer}
    target = out / "decisions" / (identifier + "-" + str(uuid4()) + ".json")
    save(target, result)
    return {"path": str(target), "recorded_at": result["recorded_at"]}


